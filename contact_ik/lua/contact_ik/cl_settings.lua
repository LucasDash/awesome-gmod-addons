hook.Add("PopulateToolMenu","ContactIK.Settings",function()
    spawnmenu.AddToolMenuOption("Utilities","User","ContactIK","Contact IK","","",function(panel)
        panel:Help("Hold Use (E by default) for player world-model contact. Native carried props keep contact after releasing E. NPCs react automatically.")
        panel:CheckBox("Native NPCs","contact_ik_npcs")
        panel:CheckBox("Enable Contact IK","contact_ik_enabled")
        panel:CheckBox("Players","contact_ik_players")
        panel:CheckBox("Require held Use (E) for players","contact_ik_require_use")
        panel:CheckBox("Touch objects carried with native Use","contact_ik_native_carry")
        panel:CheckBox("Bring carried props into hand reach (visual only)","contact_ik_carry_alignment")
        panel:Help("Carry alignment moves the rendered prop only. Its collision and native pickup position stay unchanged.")
        panel:CheckBox("Allow free-hand contact with weapons","contact_ik_weapons")
        panel:NumSlider("Contact distance","contact_ik_distance",2,24,0)
        panel:NumSlider("Evaluation distance","contact_ik_range",128,2000,0)
        panel:CheckBox("Speed-sensitive bracing","contact_ik_speed_brace")
        panel:NumSlider("Finger settling strength","contact_ik_finger_settle",0,1,2)
        panel:NumSlider("Pose transition time","contact_ik_transition_time",.08,.4,2)
        panel:NumSlider("Release fade time","contact_ik_fade_time",.15,1.5,2)
        panel:Help("World-model posing only. No first-person viewmodel or NPC navigation changes.")
        panel:Help("Weapons normally keep the right hand; attacking, aiming and reloading take priority. Disable Require held Use to restore automatic player contact.")
    end)
end)
